import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, '..');
const binDir = path.join(rootDir, 'dist', 'bin');

function runCargo(args) {
  execFileSync('cargo', args, { cwd: rootDir, stdio: 'inherit' });
}

function getInstalledTargets() {
  try {
    const out = execFileSync('rustup', ['target', 'list', '--installed'], {
      cwd: rootDir,
      encoding: 'utf8',
    });
    return new Set(out.split(/\r?\n/).map((s) => s.trim()).filter(Boolean));
  } catch {
    return new Set();
  }
}

fs.mkdirSync(binDir, { recursive: true });

// 1. Build nonepwd-core WASM module
console.log('[build-rust] Building nonepwd-core (wasm32-unknown-unknown)...');
runCargo(['build', '-p', 'nonepwd-core', '--target', 'wasm32-unknown-unknown', '--release']);

const wasmPath = path.join(
  rootDir,
  'target',
  'wasm32-unknown-unknown',
  'release',
  'nonepwd_core.wasm'
);
const wasmBytes = fs.readFileSync(wasmPath);
const wasmB64 = wasmBytes.toString('base64');
const embeddedTsPath = path.join(rootDir, 'packages', 'core', 'src', 'wasm-embedded.ts');
fs.writeFileSync(
  embeddedTsPath,
  `// Auto-generated by scripts/build-rust.mjs from crates/nonepwd-core (wasm32-unknown-unknown)\nexport const NONEPWD_CORE_WASM_B64 = "${wasmB64}";\n`,
  'utf8'
);
console.log(
  `[build-rust] Embedded nonepwd_core.wasm (${(wasmBytes.length / 1024).toFixed(1)} KiB) -> packages/core/src/wasm-embedded.ts`
);

// 2. Build native host CLI binary (`np`)
console.log(`[build-rust] Building native nonepwd-cli (${process.platform}/${process.arch})...`);
runCargo(['build', '-p', 'nonepwd-cli', '--release']);
const hostExt = process.platform === 'win32' ? '.exe' : '';
const builtHostBin = path.join(rootDir, 'target', 'release', `np${hostExt}`);
const hostArch = process.arch === 'x64' ? 'x86_64' : process.arch;
const hostTargetBin = path.join(binDir, `np-${process.platform}-${hostArch}${hostExt}`);
const defaultBin = path.join(binDir, `np${hostExt}`);

fs.copyFileSync(builtHostBin, hostTargetBin);
fs.copyFileSync(builtHostBin, defaultBin);
if (process.platform !== 'win32') {
  fs.chmodSync(hostTargetBin, 0o755);
  fs.chmodSync(defaultBin, 0o755);
}
console.log(`[build-rust] Built host binary -> ${path.relative(rootDir, hostTargetBin)}`);

// 3. Cross-compile Linux musl static binary when installed (e.g. from macOS)
const installedTargets = getInstalledTargets();
if (installedTargets.has('x86_64-unknown-linux-musl')) {
  console.log('[build-rust] Cross-compiling static Linux x86_64 binary (x86_64-unknown-linux-musl)...');
  runCargo(['build', '-p', 'nonepwd-cli', '--target', 'x86_64-unknown-linux-musl', '--release']);
  const linuxSrc = path.join(rootDir, 'target', 'x86_64-unknown-linux-musl', 'release', 'np');
  const linuxDst = path.join(binDir, 'np-linux-x86_64');
  fs.copyFileSync(linuxSrc, linuxDst);
  fs.chmodSync(linuxDst, 0o755);
  console.log(`[build-rust] Built static Linux binary -> ${path.relative(rootDir, linuxDst)}`);
}

if (installedTargets.has('aarch64-unknown-linux-musl')) {
  console.log('[build-rust] Cross-compiling static Linux arm64 binary (aarch64-unknown-linux-musl)...');
  runCargo(['build', '-p', 'nonepwd-cli', '--target', 'aarch64-unknown-linux-musl', '--release']);
  const linuxArmSrc = path.join(rootDir, 'target', 'aarch64-unknown-linux-musl', 'release', 'np');
  const linuxArmDst = path.join(binDir, 'np-linux-arm64');
  fs.copyFileSync(linuxArmSrc, linuxArmDst);
  fs.chmodSync(linuxArmDst, 0o755);
  console.log(`[build-rust] Built static Linux arm64 binary -> ${path.relative(rootDir, linuxArmDst)}`);
}
